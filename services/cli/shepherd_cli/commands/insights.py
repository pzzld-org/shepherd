def _dispatch(argv: list[str]) -> int:
    """Dispatch on ``argv[0]`` exactly like ``cmd_insights.sh``'s ``case`` statement.

    Args:
        argv: The raw remaining command-line tokens after ``insights``,
            e.g. ``["list", "--json"]`` or ``[]``.

    Returns:
        The bash-parity process exit code for whichever subcommand ran
        (or the bare/help/unknown-subcommand arms).
    """
    sub = argv[0] if argv else ""
    rest = argv[1:]

    if sub == "list":
        return _cmd_list(rest)
    if sub == "show":
        return _cmd_show(rest)
    if sub == "export":
        return _cmd_export(rest)
    if sub == "clear":
        return _cmd_clear(rest)
    if sub in ("", "-h", "--help"):
        typer.echo(_USAGE)
        return 0

    typer.echo(f"ERROR: unknown subcommand: {sub}", err=True)
    typer.echo(_USAGE, err=True)
    return 1


@app.callback(invoke_without_command=True, context_settings={"ignore_unknown_options": True, "help_option_names": []})
def insights(
    args: list[str] = typer.Argument(
        None,
        help=(
            "Subcommand + args: 'list [--sprint=B] [--kind=K] [--actioned|--unactioned] "
            "[--json|--md]' | 'show <id> [--json]' | 'export [--sprint=B] [--md]' | "
            "'clear [--older-than-days=N]'. Defaults to usage/help."
        ),
    ),
) -> None:
    """Cross-lane INSIGHTS registry — native port of ``shctx insights``.

    See the module docstring for why this is ONE variadic callback rather
    than four ``@app.command()``s: bash's default-to-usage, exit-1-on-
    unknown-subcommand, and per-subcommand-``ERROR:-unknown-arg`` contracts
    don't match Typer/Click's own subcommand-dispatch defaults.

    Args:
        args: Every token after ``insights`` on the command line, in
            order, with NOTHING pre-parsed as flags/options by Click (see
            ``context_settings={"ignore_unknown_options": True}`` on this
            callback). ``None``/empty means a bare ``shepherd insights`` —
            dispatched as the usage/help arm, per bash's ``""|-h|--help)
            usage; exit 0 ;;``.
    """
    raise typer.Exit(code=_dispatch(list(args or [])))


